function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (!el.dataset.hydrated) {
      el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon, Number(el.dataset.size) || 16));
      el.dataset.hydrated = '1';
    }
  });
}
